# ✅ Date normalization function
def normalize_date(date_str):
    try:
        if "/" in date_str:
            day, month, year = date_str.split("/")[:3]
            return f"{year}-{month.zfill(2)}-{day.zfill(2)}"
        return date_str  # Assume already in correct format
    except:
        return date_str

