# === Core Inference Function ===
def filter_top_by_class(instances):
    if len(instances) == 0:
        return instances
    selected = []
    boxes = instances.pred_boxes.tensor
    scores = instances.scores
    classes = instances.pred_classes
    by_class = defaultdict(list)
    for idx, cls in enumerate(classes):
        by_class[int(cls)].append(idx)
    for cls, idxs in by_class.items():
        cls_boxes = boxes[idxs]
        cls_scores = scores[idxs]
        keep = nms(cls_boxes, cls_scores, 0.5)
        if keep.numel() > 0:
            best_idx = idxs[keep[cls_scores[keep].argmax()].item()]
            selected.append(best_idx)
    return instances[selected] if selected else instances[[]]

def detect_and_estimate_cost(image_path, car_model):
    img = cv2.imread(image_path)
    if img is None:
        raise FileNotFoundError(f"Could not load image: {image_path}")
    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
    part_outputs = predictor_parts(img)
    severity_outputs = predictor_sev(img)
    part_instances = filter_top_by_class(part_outputs["instances"].to("cpu"))
    all_sev_instances = severity_outputs["instances"].to("cpu")
    if len(all_sev_instances) > 0:
        top_idx = all_sev_instances.scores.argmax().item()
        severity_instances = all_sev_instances[top_idx:top_idx+1]

    else:
        severity_instances = all_sev_instances
    part_boxes = part_instances.pred_boxes.tensor if part_instances.has("pred_boxes") else []
    part_classes = part_instances.pred_classes.tolist()
    part_scores = part_instances.scores.tolist() if part_instances.has("scores") else [1.0] * len(part_classes)
    sev_boxes = severity_instances.pred_boxes.tensor if severity_instances.has("pred_boxes") else []
    sev_classes = severity_instances.pred_classes.tolist()
    matched = {}
    if len(part_boxes):
        iou = box_iou(part_boxes, sev_boxes) if len(sev_boxes) else None
        for i, part_cls in enumerate(part_classes):
            part_name = metadata_parts.thing_classes[part_cls]
            if part_name == "car":
                continue
            score = part_scores[i]
            severity = "moderate"
            if iou is not None and len(sev_classes):
                best_match = iou[i].argmax().item()
                if iou[i][best_match] > 0.5:
                    severity = metadata_sev.thing_classes[sev_classes[best_match]]
            if (part_name not in matched) or (matched[part_name][2] < score):
                matched[part_name] = (part_name, severity, score)
    if not matched and part_classes and sev_classes:
        part_name = metadata_parts.thing_classes[part_classes[0]]
        sev = metadata_sev.thing_classes[sev_classes[0]]
        if part_name != "car":
            matched[part_name] = (part_name, sev, 1.0)
    matched = [(p, s) for p, s, _ in matched.values()]
    row = {p: "none" for p in all_parts}
    for part, severity in matched:
        row[part] = severity
    row["car_model"] = car_model
    for part in all_parts:
        row[part] = severity_map.get(row[part], 0)
    input_df = pd.DataFrame([row])
    encoded_model = encoder.transform(input_df[["car_model"]])
    encoded_df = pd.DataFrame(encoded_model, columns=encoder.get_feature_names_out(["car_model"]))
    info = get_group_info(car_model)
    input_df["labor_paint"] = info["labor_paint"]
    input_df["num_damaged_parts"] = sum([1 for p in all_parts if row[p] > 0])
    input_df["severity_score"] = sum([row[p] for p in all_parts])
    X_input = pd.concat([
        input_df[all_parts],
        encoded_df,
        input_df[["labor_paint", "num_damaged_parts", "severity_score"]]
    ], axis=1)
    predicted_cost = float(model.predict(X_input)[0])
    manual_total = 0
    breakdown = []
    for part, severity in matched:
        base = base_costs.get(part, 10000)
        sev_mult = severity_multipliers.get(severity, 1.0)
        total = base * sev_mult * info["multiplier"] + info["labor_paint"]
        breakdown.append({
            "part": part, "severity": severity, "base": int(base),
            "mult": float(sev_mult), "labor": int(info["labor_paint"]), "total": float(total)
        })
        manual_total += total
    out_part = Visualizer(img_rgb.copy(), metadata=metadata_parts, scale=1.0).draw_instance_predictions(part_instances)
    out_sev = Visualizer(img_rgb.copy(), metadata=metadata_sev, scale=1.0).draw_instance_predictions(severity_instances)
    return {
        "predicted_cost": predicted_cost,
        "manual_cost": manual_total,
        "car_model": car_model,
        "damages": breakdown,
        "part_image_base64": encode_img(out_part.get_image()[:, :, ::-1]),
        "severity_image_base64": encode_img(out_sev.get_image()[:, :, ::-1])
    }

